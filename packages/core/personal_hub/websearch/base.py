"""Веб-поиск для обоснования ответов модели (Этап 1, опционально).

Назначение: дать модели свежий контекст из интернета и показать пользователю
источники. Модуль нейтрален к поисковику: конкретные реализации подключаются
через протокол `WebSearchProvider` и реестр.

Место в архитектуре: самостоятельный сервис рядом с провайдерами LLM. Он НЕ
является адаптером провайдера модели: поиск выполняется до обращения к LLM, а
результаты подмешиваются в системную инструкцию. Так бизнес-логика не зависит
от того, какой LLM выбран.

Ключевые инварианты:
1. Результаты поиска — недоверенный ввод. Они оборачиваются в разделители и
   сопровождаются явной инструкцией считать их данными, а не командами.
2. Один пользовательский запрос = не более одного поиска. Автоматические
   «уточняющие» поиски модели запрещены: это неуправляемый рост расходов.
3. Контекст ограничен по числу результатов и длине: токены поиска входят в
   вход запроса и должны учитываться в оценке бюджета.
"""
from __future__ import annotations

from dataclasses import dataclass, field
from typing import Protocol


@dataclass(frozen=True)
class WebSearchResult:
    """Один результат поиска.

    Attributes:
        title: Заголовок страницы.
        url: Адрес источника.
        snippet: Краткий фрагмент текста для контекста модели.
        engine: Поисковый движок, отдавший результат (для диагностики).
    """

    title: str
    url: str
    snippet: str
    engine: str = ""


@dataclass
class WebSearchResponse:
    """Итог поискового запроса.

    Attributes:
        query: Фактически выполненный запрос (после нормализации).
        results: Найденные результаты в порядке релевантности.
        warnings: Некритичные замечания (например, часть движков не ответила).
    """

    query: str
    results: list[WebSearchResult] = field(default_factory=list)
    warnings: list[str] = field(default_factory=list)


@dataclass(frozen=True)
class WebCitation:
    """Источник, показанный пользователю под ответом.

    Нумерация (`index`) совпадает с маркерами `[n]` в тексте ответа, поэтому
    пользователь может сопоставить утверждение и источник.
    """

    index: int
    title: str
    url: str
    snippet: str


class WebSearchError(Exception):
    """Ошибка веб-поиска со стабильным машинным кодом.

    Attributes:
        code: Стабильный код для UI и логов.
        message: Понятное пользователю описание.
        retryable: Имеет ли смысл повторить запрос.
    """

    def __init__(self, code: str, message: str, retryable: bool = False) -> None:
        super().__init__(message)
        self.code = code
        self.message = message
        self.retryable = retryable


